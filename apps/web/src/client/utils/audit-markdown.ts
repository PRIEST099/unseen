import type { ClassifiedAudit, Haunting, HauntingSeverity, HauntingType } from '@the-unseen/core'
import { hauntingDisplayName, HAUNTING_TYPE_ORDER, mostSevere, SEVERITY_ORDER } from './haunting-display'
import { manualCheckLabel } from './manual-check'
import { groupByWCAG } from './wcag-groups'

export const CLEAN_SITE_MESSAGE = 'No hauntings found by automated checks; a manual review is still needed.'

export const HONESTY_CAVEAT =
  'This report lists what automated checks found. It is not a statement that the site meets or fails WCAG 2.2, and it is not a substitute for a manual review with real assistive technology.'

const SEVERITY_LABELS: Record<HauntingSeverity, string> = {
  Wraith: 'Wraith (critical)',
  Restless: 'Restless (warnings)',
  Banished: 'Banished (minor)',
}

function plural(count: number, noun: string): string {
  return `${count} ${noun}${count === 1 ? '' : 's'}`
}

/** One-line code span that survives backticks and newlines inside the text. */
export function inlineCode(text: string): string {
  const flat = text.replace(/\s+/g, ' ').trim()
  const longestRun = Math.max(0, ...(flat.match(/`+/g) ?? []).map((run) => run.length))
  const fence = '`'.repeat(longestRun + 1)
  const padded = flat.startsWith('`') || flat.endsWith('`') ? ` ${flat} ` : flat
  return `${fence}${padded}${fence}`
}

/** A fenced block whose fence is longer than any backtick run in the code. */
export function fencedBlock(code: string, language = 'html'): string {
  const longestRun = Math.max(0, ...(code.match(/`+/g) ?? []).map((run) => run.length))
  const fence = '`'.repeat(Math.max(3, longestRun + 1))
  return `${fence}${language}\n${code}\n${fence}`
}

function groupByType(hauntings: readonly Haunting[]): Array<[HauntingType, Haunting[]]> {
  const byType = new Map<HauntingType, Haunting[]>()
  for (const haunting of hauntings) byType.set(haunting.type, [...(byType.get(haunting.type) ?? []), haunting])
  const ordered: Array<[HauntingType, Haunting[]]> = []
  for (const type of HAUNTING_TYPE_ORDER) {
    const instances = byType.get(type)
    if (instances !== undefined) ordered.push([type, instances])
  }
  return ordered
}

function summaryLines(audit: ClassifiedAudit): string[] {
  const count = (severity: HauntingSeverity): number => audit.hauntings.filter((haunting) => haunting.severity === severity).length
  return [
    ...SEVERITY_ORDER.map((severity) => `- ${count(severity)} ${SEVERITY_LABELS[severity]}`),
    '',
    `**Total hauntings detected**: ${audit.hauntings.length}`,
  ]
}

function findingLines(audit: ClassifiedAudit): string[] {
  if (audit.hauntings.length === 0) return [CLEAN_SITE_MESSAGE]
  const lines: string[] = []
  for (const group of groupByWCAG(audit.hauntings)) {
    const { criterion } = group
    lines.push(`### ${criterion.id} ${criterion.title} (${criterion.level})`, '', `[Understanding ${criterion.id}](${criterion.url})`, '')
    for (const [type, instances] of groupByType(group.hauntings)) {
      const severity = mostSevere(instances.map((haunting) => haunting.severity))
      lines.push(`#### ${hauntingDisplayName(type)} (${plural(instances.length, 'element')}, ${severity})`, '')
      for (const haunting of instances) {
        lines.push(`- ${inlineCode(haunting.htmlSnippet === '' ? hauntingDisplayName(type) : haunting.htmlSnippet)}`)
        lines.push(`  **Fix**: ${haunting.fix.instruction.replace(/\s+/g, ' ').trim()}`)
      }
      lines.push('')
    }
  }
  return lines
}

function manualCheckLines(audit: ClassifiedAudit): string[] {
  if (audit.needsManualCheck.length === 0) return ['No elements were flagged for manual review.']
  return audit.needsManualCheck.map((node) => `- **${manualCheckLabel(node.reason)}**: ${inlineCode(node.htmlSnippet)}`)
}

/** The Markdown export: score, summary, coverage note, findings by criterion, manual checks. */
export function buildMarkdown(audit: ClassifiedAudit): string {
  const lines = [
    '# THE UNSEEN Audit Report',
    '',
    `**URL**: ${audit.raw.auditedUrl}`,
    `**Audited**: ${audit.raw.auditedAt}`,
    `**Haunting Score**: ${audit.score}/100`,
    '',
    '## Summary',
    '',
    ...summaryLines(audit),
    '',
    '---',
    '',
    '## Coverage Note',
    '',
    audit.automatedCoverageNote,
    '',
    HONESTY_CAVEAT,
    '',
    '---',
    '',
    '## Findings by WCAG Criterion',
    '',
    ...findingLines(audit),
    '---',
    '',
    '## Needs Manual Check',
    '',
    ...manualCheckLines(audit),
    '',
    '---',
    '',
    'Generated by THE UNSEEN',
    '',
  ]
  return lines.join('\n')
}

/** The JSON export: the ClassifiedAudit exactly as the client received it, two-space indented. */
export function buildJson(audit: ClassifiedAudit): string {
  return JSON.stringify(audit, null, 2)
}
